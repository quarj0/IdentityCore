#!/usr/bin/env python3
"""Generate explicit governed-resource SDK methods from the supported route manifest."""

import argparse
import json
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[1]
HEADER = "Generated by scripts/generate_governed_sdk.py. DO NOT EDIT."


def camel(name):
    first, *rest = name.split("_")
    return first + "".join(word.title() for word in rest)


def generate():
    methods = json.loads((ROOT / "sdk/governed-operations.json").read_text())
    contract = yaml.safe_load(
        (ROOT / "docs/openapi/identitycore-public-api.yaml").read_text()
    )
    documented = {
        (method.upper(), path)
        for path, value in contract["paths"].items()
        if path.startswith(("/evidence/", "/claims/", "/providers/"))
        for method in value
        if method in {"get", "post"}
    }
    expected = documented - {("POST", "/providers/operations/{operation_id}/callback")}
    if expected != {(op["method"], op["path"]) for op in methods}:
        raise ValueError("Governed SDK route manifest differs from the public contract")
    py = [
        f'"""{HEADER}"""',
        "from urllib.parse import quote, urlencode",
        "from uuid import uuid4",
        "",
        "class GovernedResources:",
        "    def __init__(self, client):",
        "        self._client = client",
        "",
    ]
    js = [
        f"// {HEADER}",
        'import { randomUUID } from "node:crypto";',
        "",
        "export class GovernedResources {",
        "  constructor(client) { this.client = client; }",
    ]
    ts = [
        f"// {HEADER}",
        'import type { RequestOptions } from "./index.js";',
        "export interface GovernedRequestOptions extends RequestOptions { query?: Record<string, string | number | boolean>; disclosureToken?: string; }",
        "export class GovernedResources {",
    ]
    java = [
        f"// {HEADER}",
        "package io.identitycore;",
        "import com.fasterxml.jackson.databind.JsonNode;",
        "import java.net.URLEncoder;",
        "import java.nio.charset.StandardCharsets;",
        "import java.util.Map;",
        "import java.util.UUID;",
        "public final class GovernedResources {",
        "  private final IdentityCoreClient client;",
        "  GovernedResources(IdentityCoreClient client) { this.client = client; }",
        '  private static String segment(String value) { return URLEncoder.encode(value, StandardCharsets.UTF_8).replace("+", "%20"); }',
        '  private static String query(Map<String, ?> values) { if (values == null || values.isEmpty()) return ""; return "?" + values.entrySet().stream().filter(e -> e.getValue() != null).map(e -> segment(e.getKey()) + "=" + segment(e.getValue().toString())).collect(java.util.stream.Collectors.joining("&")); }',
    ]
    cs = [
        f"// {HEADER}",
        "using System.Text.Json;",
        "namespace IdentityCore;",
        "public sealed class GovernedResources {",
        "  private readonly IdentityCoreClient client;",
        "  internal GovernedResources(IdentityCoreClient client) { this.client = client; }",
        '  private static string Query(IReadOnlyDictionary<string, object?>? query) => query is null || query.Count == 0 ? "" : "?" + string.Join("&", query.Where(x => x.Value is not null).Select(x => Uri.EscapeDataString(x.Key) + "=" + Uri.EscapeDataString(x.Value!.ToString()!)));',
    ]
    for operation in methods:
        name, method, path = (operation[key] for key in ("name", "method", "path"))
        parameters = re.findall(r"{([^}]+)}", path)
        post = method == "POST"
        redeem = name == "redeem_claim_disclosure"
        py_args = ", ".join(
            [
                "self",
                *parameters,
                *(["body"] if post else []),
                "*",
                "query=None",
                *(["idempotency_key=None"] if post else []),
                *(["disclosure_token"] if redeem else []),
            ]
        )
        py_path = path
        for param in parameters:
            py_path = py_path.replace(
                "{" + param + "}", "{quote(str(" + param + '), safe="")}'
            )
        py += [
            f"    def {name}({py_args}):",
            f"        path = f'{py_path}'",
            "        if query:",
            '            path += "?" + urlencode(query)',
            f'        return self._client.request("{method}", path'
            + (", body" if post else "")
            + (
                ', idempotency_key=idempotency_key or "ik_" + uuid4().hex'
                if post
                else ""
            )
            + (', headers={"X-Disclosure-Token": disclosure_token}' if redeem else "")
            + ")",
            "",
        ]
        js_args = [*parameters, *(["body"] if post else []), "options = {}"]
        js_path = path
        for param in parameters:
            js_path = js_path.replace(
                "{" + param + "}", "${encodeURIComponent(" + param + ")}"
            )
        js += [
            "  " + camel(name) + "(" + ", ".join(js_args) + ") {",
            *(
                [
                    '    if (typeof options.disclosureToken !== "string" || !options.disclosureToken) throw new TypeError("A disclosure token is required.");'
                ]
                if redeem
                else []
            ),
            f"    const path = `{js_path}`;",
            "    const query = new URLSearchParams(Object.entries(options.query ?? {}).filter(([, value]) => value !== undefined && value !== null).map(([key, value]) => [key, String(value)])).toString();",
            f'    return this.client.request("{method}", path + (query ? "?" + query : ""), '
            + ("body" if post else "undefined")
            + ", { ...options"
            + (
                ', idempotencyKey: options.idempotencyKey || `ik_${randomUUID().replaceAll("-", "")}`'
                if post
                else ""
            )
            + (
                ', headers: { ...options.headers, "X-Disclosure-Token": options.disclosureToken }'
                if redeem
                else ""
            )
            + " });",
            "  }",
        ]
        typed_op = contract["paths"][path][method.lower()]
        body_type = (
            typed_op.get("requestBody", {})
            .get("content", {})
            .get("application/json", {})
            .get("schema", {})
            .get("$ref", "")
            .rsplit("/", 1)[-1]
        )
        response = next(
            v for k, v in typed_op["responses"].items() if k.startswith("2")
        )["content"]["application/json"]["schema"]["properties"]["data"]["$ref"].rsplit(
            "/", 1
        )[-1]
        # Keep type references local to the generated declarations to avoid cycles.
        ts.append(
            "  "
            + camel(name)
            + "("
            + ", ".join(
                [
                    *(param + ": string" for param in parameters),
                    *(['body: import("./models.js").' + body_type] if post else []),
                    "options: GovernedRequestOptions & { disclosureToken: string }"
                    if redeem
                    else "options?: GovernedRequestOptions",
                ]
            )
            + '): Promise<import("./models.js").'
            + response
            + ">;"
        )
        java_args = [
            *("String " + param for param in parameters),
            *(["JsonNode body", "String idempotencyKey"] if post else []),
            "Map<String, ?> query",
            *(["String disclosureToken"] if redeem else []),
        ]
        java_path = '"' + path + '"'
        for param in parameters:
            java_path = java_path.replace(
                "{" + param + "}", '" + segment(' + param + ') + "'
            )
        java.append(
            "  public JsonNode "
            + camel(name)
            + "("
            + ", ".join(java_args)
            + ') { return client.request("'
            + method
            + '", '
            + java_path
            + " + query(query), "
            + ("body" if post else "null")
            + ", "
            + (
                '(idempotencyKey == null || idempotencyKey.isBlank() ? "ik_" + UUID.randomUUID().toString().replace("-", "") : idempotencyKey)'
                if post
                else "null"
            )
            + (', Map.of("X-Disclosure-Token", disclosureToken)' if redeem else "")
            + "); }"
        )
        cs_args = [
            *("string " + param for param in parameters),
            *(["object body"] if post else []),
            *(["string disclosureToken"] if redeem else []),
            "IReadOnlyDictionary<string, object?>? query = null",
            *(["string? idempotencyKey = null"] if post else []),
            "CancellationToken cancellationToken = default",
        ]
        cs_path = '$"' + re.sub(r"{([^}]+)}", r"{Uri.EscapeDataString(\1)}", path) + '"'
        cs.append(
            "  public Task<JsonElement> "
            + camel(name)[0].upper()
            + camel(name)[1:]
            + "Async("
            + ", ".join(cs_args)
            + ") => client.SendAsync(HttpMethod."
            + ("Post" if post else "Get")
            + ", "
            + cs_path
            + " + Query(query), "
            + ("body" if post else "null")
            + ", "
            + (
                'idempotencyKey ?? "ik_" + Guid.NewGuid().ToString("N")'
                if post
                else "null"
            )
            + (
                ', new Dictionary<string, string> { ["X-Disclosure-Token"] = disclosureToken }'
                if redeem
                else ""
            )
            + ", cancellationToken);"
        )
    js.append("}")
    ts.append("}")
    java.append("}")
    cs.append("}")
    return {
        "sdk/python/identitycore/governed.py": "\n".join(py) + "\n",
        "sdk/javascript/src/governed.js": "\n".join(js) + "\n",
        "sdk/javascript/src/governed.d.ts": "\n".join(ts) + "\n",
        "sdk/java/src/main/java/io/identitycore/GovernedResources.java": "\n".join(java)
        + "\n",
        "sdk/dotnet/src/IdentityCore/GovernedResources.cs": "\n".join(cs) + "\n",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for name, contents in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                mismatches.append(name)
        else:
            path.write_text(contents)
    if mismatches:
        raise SystemExit(
            "Generated governed SDK files differ: " + ", ".join(mismatches)
        )
    print(
        "Governed SDK methods cover every supported resource operation in four languages."
    )


if __name__ == "__main__":
    main()
